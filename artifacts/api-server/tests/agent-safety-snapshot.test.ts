import { afterAll, beforeEach, describe, expect, it, vi } from 'vitest';
import { prisma } from '../src/lib/prisma';
import { loginAs, resetDatabase, seedFixture, type Fixture } from './helpers';
import request from 'supertest';
import app from '../src/app';

describe('demo safety and auditable snapshots', () => {
  let fx: Fixture;
  beforeEach(async () => { process.env.MIRFAQ_AUTONOMY_DEMO = '1'; await resetDatabase(); fx = await seedFixture('aamal', 'a', 'org-demo'); await prisma.technicianProfile.update({ where: { id: fx.technicianProfileId }, data: { specialty: 'تكييف' } }); await prisma.agentAvailability.create({ data: { organizationId: fx.organizationId, technicianId: fx.technicianProfileId, available: true } }); });
  afterAll(async () => { delete process.env.MIRFAQ_AUTONOMY_DEMO; await prisma.$disconnect(); });
  async function setup(description = 'تسريب ماء قرب لوحة الكهرباء') {
    const ticket = await prisma.maintenanceRequest.create({ data: { title: 'بلاغ تجريبي', description, category: 'تكييف', priority: 'عادي', status: 'معلّقة', propertyId: fx.propertyId, unitId: fx.unitId, residentId: fx.residentId, organizationId: fx.organizationId } });
    const asset = await prisma.agentAsset.create({ data: { organizationId: fx.organizationId, unitId: fx.unitId, tag: 'AC-TEST', kind: 'hvac' } });
    const manager = await loginAs(fx.managerEmail);
    const input = { requestId: ticket.id, assetId: asset.id, issueCode: 'hvac_leak', priority: 'normal', riskConfirmedSafe: true, availableTechnicianIds: [fx.technicianProfileId] };
    return { ticket, manager, input };
  }
  async function contain(manager: Awaited<ReturnType<typeof loginAs>>, id: string) {
    const context = (await manager.get(`/api/agent/safety/${id}`)).body;
    const body = { fingerprint: context.fingerprint, expectedOrderRevision: context.orderRevision, expectedRequestVersion: context.requestVersion, reasonCode: 'demo_isolation', evidenceRef: 'DEMO-TEST-001', confirmedSynthetic: true };
    const result = await manager.post(`/api/agent/safety/${id}/containment`).send(body);
    return { context, body, result };
  }
  it('requires an authorized, versioned synthetic claim and separate reassessment', async () => {
    const { ticket, manager, input } = await setup();
    const tech = await loginAs(fx.technicianEmail);
    const c = await contain(manager, ticket.id);
    expect(c.result.body).toMatchObject({ state: 'pending_reassessment', proofOfContainment: false });
    expect((await tech.post(`/api/agent/safety/${ticket.id}/containment`).send(c.body)).status).toBe(403);
    expect((await manager.post(`/api/agent/safety/${ticket.id}/containment`).send({ ...c.body, evidenceRef: '' })).status).toBe(400);
    expect((await manager.post('/api/agent/plan').send(input)).body.state).toBe('escalate');
    const reassess = await manager.post(`/api/agent/safety/${ticket.id}/reassess`).send({ reviewId: c.result.body.reviewId, confirmedReassessment: true });
    expect(reassess.body).toMatchObject({ state: 'reassessed', automaticAssignment: false, proofOfContainment: false });
    expect(await prisma.agentOrder.count()).toBe(0);
    await prisma.maintenanceRequest.update({ where: { id: ticket.id }, data: { priority: 'عاجل' } });
    expect((await manager.post('/api/agent/plan').send(input)).body.state).toBe('escalate');
    expect((await manager.post(`/api/agent/safety/${ticket.id}/containment`).send(c.body)).body.state).toBe('stale');
    expect(await prisma.agentOrder.count()).toBe(0);
    const audit = (await manager.get('/api/agent/audit')).body as Array<{ action: string; outcome: string }>;
    expect(audit.some(x => x.action === 'plan' && x.outcome === 'escalated')).toBe(true);
    expect(audit.some(x => x.action === 'authorization' && x.outcome === 'denied')).toBe(true);
  });
  it('consumes reassessment on assignment and a new risk invalidates the receipt', async () => {
    const { ticket, manager, input } = await setup();
    const c = await contain(manager, ticket.id);
    await manager.post(`/api/agent/safety/${ticket.id}/reassess`).send({ reviewId: c.result.body.reviewId, confirmedReassessment: true });
    const plan = await manager.post('/api/agent/plan').send(input);
    expect(plan.body.state).toBe('ready');
    const order = await manager.post('/api/agent/orders').set('Idempotency-Key', 'safety_test_key_00001').send({ ...input, planToken: plan.body.planToken });
    expect(order.body.state).toBe('verified');
    expect((await manager.get('/api/agent/orders/by-key/safety_test_key_00001')).body.state).toBe('verified');
    const intake = await manager.post('/api/agent/intakes').send({ requestId: ticket.id });
    await manager.post(`/api/agent/intakes/${intake.body.id}/answers`).send({ text: 'شرر ودخان قرب الكهرباء' });
    expect((await manager.get('/api/agent/orders/by-key/safety_test_key_00001')).body.state).toBe('escalate');
  });
  it('requires a fresh containment review before reassigning a hazardous order', async () => {
    const { ticket, manager, input } = await setup();
    const firstReview = await contain(manager, ticket.id);
    await manager.post(`/api/agent/safety/${ticket.id}/reassess`).send({ reviewId: firstReview.result.body.reviewId, confirmedReassessment: true });
    const plan = await manager.post('/api/agent/plan').send(input);
    const created = await manager.post('/api/agent/orders').set('Idempotency-Key', 'risk_replan_create_01').send({ ...input, planToken: plan.body.planToken });
    const order = created.body.order;
    await prisma.agentDemoPolicy.create({ data: { organizationId: fx.organizationId, enabled: false, issueCodesJson: '[]', urgentWordsJson: '[]', maxWorkload: 4 } });
    const oldUser = await prisma.user.findUniqueOrThrow({ where: { id: fx.technicianUserId } });
    const user = await prisma.user.create({ data: { name: 'بديل تجريبي', email: 'backup@test.invalid', passwordHash: oldUser.passwordHash, role: 'technician', organizationId: fx.organizationId } });
    const replacement = await prisma.technicianProfile.create({ data: { userId: user.id, specialty: 'تكييف' } });
    await prisma.agentAvailability.create({ data: { organizationId: fx.organizationId, technicianId: replacement.id, available: true } });
    const replan = () => manager.post(`/api/agent/orders/${order.id}/replan`).set('Idempotency-Key', 'risk_replan_key_0001').send({ reason: 'technician_absent', expectedRevision: order.revision });
    expect((await replan()).body.state).toBe('review');
    const newReview = await contain(manager, ticket.id);
    expect(newReview.context.orderRevision).toBe(order.revision);
    await manager.post(`/api/agent/safety/${ticket.id}/reassess`).send({ reviewId: newReview.result.body.reviewId, confirmedReassessment: true });
    expect((await replan()).body).toMatchObject({ state: 'reassigned', order: { technicianId: replacement.id } });
    expect((await replan()).body).toMatchObject({ state: 'reassigned', replay: true });
    expect((await manager.get('/api/agent/commands/by-key/risk_replan_key_0001')).body.state).toBe('reassigned');
    expect(await prisma.agentOrder.count()).toBe(1);
  });
  it('saves a tenant-scoped immutable snapshot without free text and records safe audit codes', async () => {
    const { ticket, manager, input } = await setup('تسريب ماء من المكيف');
    await prisma.maintenanceRequest.update({ where: { id: ticket.id }, data: { title: 'SYNTHETIC-SECRET-DO-NOT-LOG' } });
    const plan = await manager.post('/api/agent/plan').send(input);
    const order = await manager.post('/api/agent/orders').set('Idempotency-Key', 'snapshot_order_key_01').send({ ...input, planToken: plan.body.planToken });
    expect(order.body.state).toBe('verified');
    const first = await manager.post('/api/agent/report/snapshots');
    expect(first.status).toBe(201);
    expect(first.body.generatedAt).toBeTruthy();
    expect(first.body.total).toBe(1);
    await manager.post(`/api/agent/orders/${order.body.order.id}/block`).send({ blocker: 'part_unavailable' });
    await manager.post('/api/agent/plan').send(input);
    const tech = await loginAs(fx.technicianEmail);
    await tech.post('/api/agent/plan').send(input);
    const second = await manager.get(`/api/agent/report/snapshots/${first.body.id}`);
    expect(second.body).toEqual(first.body);
    const other = await seedFixture('aamal', 'b'); const outsider = await loginAs(other.managerEmail);
    expect((await outsider.get(`/api/agent/report/snapshots/${first.body.id}`)).status).toBe(404);
    const audit = await manager.get('/api/agent/audit');
    expect(JSON.stringify(audit.body)).not.toContain('SYNTHETIC-SECRET-DO-NOT-LOG');
    expect(JSON.stringify(first.body)).not.toContain('SYNTHETIC-SECRET-DO-NOT-LOG');
    expect((await outsider.get('/api/agent/audit')).body).not.toEqual(audit.body);
    expect((await manager.get('/api/agent/report?cutoff=2000-01-01')).status).toBe(400);
  });
  it('keeps duplicate lookup, selection, commands, and reports within the session tenant', async () => {
    const { ticket, manager, input } = await setup('تسريب ماء من المكيف');
    const plan = await manager.post('/api/agent/plan').send(input);
    const created = await manager.post('/api/agent/orders').set('Idempotency-Key', 'tenant_same_key_00001').send({ ...input, planToken: plan.body.planToken });
    expect(created.body.state).toBe('verified');
    const other = await seedFixture('aamal', 'b'); const outsider = await loginAs(other.managerEmail);
    const ownTicket = await prisma.maintenanceRequest.create({ data: { title: 'تسريب', description: 'تسريب ماء من المكيف', category: 'تكييف', priority: 'عادي', status: 'معلّقة', propertyId: other.propertyId, unitId: other.unitId, residentId: other.residentId, organizationId: other.organizationId } });
    const ownAsset = await prisma.agentAsset.create({ data: { organizationId: other.organizationId, unitId: other.unitId, tag: 'AC-TEST', kind: 'hvac' } });
    await prisma.agentAvailability.create({ data: { organizationId: other.organizationId, technicianId: other.technicianProfileId, available: true } });
    const foreignTechnician = await outsider.post('/api/agent/plan').send({ ...input, requestId: ownTicket.id, assetId: ownAsset.id, organizationId: fx.organizationId });
    expect(foreignTechnician.body.state).toBe('clarify');
    expect(JSON.stringify(foreignTechnician.body)).not.toContain(created.body.order.id);
    expect((await outsider.get('/api/agent/orders/by-key/tenant_same_key_00001')).status).toBe(404);
    expect((await outsider.get('/api/agent/commands/by-key/tenant_same_key_00001')).status).toBe(404);
    expect((await outsider.get('/api/agent/report')).body.total).toBe(0);
    expect((await outsider.post(`/api/agent/orders/${created.body.order.id}/link`).send({ requestId: ownTicket.id, assetId: ownAsset.id, issueCode: 'hvac_leak', confirmed: true })).body.state).toBe('not_found');
    const sameOrgUser = await prisma.user.create({ data: { name: 'آخر', email: 'same-org@test.invalid', passwordHash: (await prisma.user.findUniqueOrThrow({ where: { id: fx.technicianUserId } })).passwordHash, role: 'technician', organizationId: fx.organizationId } });
    await prisma.technicianProfile.create({ data: { userId: sameOrgUser.id, specialty: 'تكييف' } });
    const otherTech = await loginAs('same-org@test.invalid');
    const report = { assetId: input.assetId, issueCode: 'hvac_leak', workPerformed: 'فحص الجهاز التجريبي', verificationResult: 'resolved', verificationNote: 'تحقق تجريبي', verificationPerformed: true, observedIssueMatches: true };
    expect((await otherTech.post(`/api/agent/orders/${created.body.order.id}/closure-report`).send(report)).status).toBe(404);
    expect((await manager.post(`/api/agent/orders/${created.body.order.id}/close`).send({ confirmReview: true })).body.state).toBe('needs_completion');
    expect((await prisma.maintenanceRequest.findUniqueOrThrow({ where: { id: ticket.id } })).technicianId).toBe(fx.technicianProfileId);
  });
  it('returns a sanitized failure even if audit storage fails too', async () => {
    const { manager, input } = await setup();
    const query = vi.spyOn(prisma.maintenanceRequest, 'findFirst').mockRejectedValueOnce(new Error('SYNTHETIC_SECRET'));
    const audit = vi.spyOn(prisma.agentAudit, 'create').mockRejectedValue(new Error('SYNTHETIC_SECRET'));
    const result = await manager.post('/api/agent/plan').send(input);
    expect(result.status).toBe(500);
    expect(result.headers['x-agent-audit-status']).toBe('outcome_unknown');
    expect(JSON.stringify(result.body)).not.toContain('SYNTHETIC_SECRET');
    const invalid = await manager.post('/api/agent/plan').send({});
    expect(invalid.status).toBe(400);
    expect(invalid.headers['x-agent-audit-status']).toBe('outcome_unknown');
    query.mockRestore(); audit.mockRestore();
  });
  it('reports unavailable intake transactions and unattributable denial without leaking data', async () => {
    const { manager, ticket } = await setup();
    const absent = await request(app).post('/api/agent/plan').send({});
    expect(absent.status).toBe(401);
    expect(absent.headers['x-agent-audit-status']).toBe('not_recorded');
    const fail = vi.spyOn(prisma, '$transaction').mockRejectedValueOnce(new Error('SYNTHETIC_SECRET'));
    const intake = await manager.post('/api/agent/intakes').send({ requestId: ticket.id });
    expect(intake.status).toBe(503);
    expect(intake.headers['x-agent-audit-status']).toBe('outcome_unknown');
    expect(JSON.stringify(intake.body)).not.toContain('SYNTHETIC_SECRET');
    expect(await prisma.agentIntake.count()).toBe(0);
    fail.mockRestore();
  });
});
